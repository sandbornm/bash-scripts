#!/usr/bin/env bash
set -euo pipefail

# Run with macOS's built-in Bash: bash setup.sh (not sudo bash setup.sh).
info() { printf '[INFO]  %s\n' "$*"; }
success() { printf '[OK]    %s\n' "$*"; }
warn() { printf '[WARN]  %s\n' "$*"; }
die() {
  printf '[ERROR] %s\n' "$*" >&2
  exit 1
}

append_once() {
  local file="$1" line="$2"
  if ! grep -Fqx -- "$line" "$file" 2>/dev/null; then
    printf '\n%s\n' "$line" >>"$file"
  fi
}

# The generated shell code expands these variables when the user opens a shell.
# shellcheck disable=SC2016
configure_shell() {
  local user_dir="$1" shell_dir="$2" brew_bin="$3" brew_prefix="$4"
  local config_dir="$user_dir/.config/mac-mini-setup"
  local source_line='[ ! -f "$HOME/.config/mac-mini-setup/env.sh" ] || . "$HOME/.config/mac-mini-setup/env.sh"'
  mkdir -p "$config_dir" "$shell_dir"

  # This file is owned by setup.sh; personal shell settings stay in .zshrc.
  {
    printf '# Generated by mac-mini setup.sh; rerunning setup replaces this file.\n'
    printf 'eval "$(%q shellenv)"\n' "$brew_bin"
    printf 'export JAVA_HOME=%q\n' "$brew_prefix/opt/openjdk@21/libexec/openjdk.jdk/Contents/Home"
    printf 'export PATH=%q:%q:%q:"$PATH"\n' \
      "$brew_prefix/opt/node@24/bin" \
      "$brew_prefix/opt/python@3.12/libexec/bin" \
      "$brew_prefix/share/google-cloud-sdk/bin"
    cat <<'EOF'
export PATH="$JAVA_HOME/bin:${CARGO_HOME:-$HOME/.cargo}/bin:$HOME/.local/bin:$PATH"
EOF
  } >"$config_dir/env.sh"

  append_once "$shell_dir/.zprofile" "$source_line"
  append_once "$shell_dir/.zshrc" "$source_line"
}

preflight() {
  [[ "$(uname -s)" == Darwin ]] || die "This script requires macOS."
  [[ "$EUID" -ne 0 ]] || die "Run as your normal user; the script calls sudo when needed."
  if [[ "$(sysctl -in sysctl.proc_translated 2>/dev/null || true)" == 1 ]]; then
    die "Open a native Apple Silicon terminal instead of running under Rosetta."
  fi
  case "${CONFIGURE_POWER:-1}" in
  0 | 1) ;;
  *) die "CONFIGURE_POWER must be 0 or 1." ;;
  esac
  if ! xcode-select -p >/dev/null 2>&1 || ! xcrun --find clang >/dev/null 2>&1; then
    xcode-select --install || true
    die "Finish installing Apple's Command Line Tools, then rerun: bash setup.sh"
  fi
}

main() {
  preflight
  SETUP_TMP_DIR="$(mktemp -d "${TMPDIR:-/tmp}/mac-mini-setup.XXXXXX")"
  trap 'rm -rf "$SETUP_TMP_DIR"' EXIT

  # 1. Find Homebrew even if the current terminal has not loaded shellenv.
  case "$(uname -m)" in
  arm64) BREW_BIN=/opt/homebrew/bin/brew ;;
  x86_64) BREW_BIN=/usr/local/bin/brew ;;
  *) die "Unsupported CPU architecture: $(uname -m)" ;;
  esac
  if [[ ! -x "$BREW_BIN" ]]; then
    info "Installing Homebrew..."
    curl -fsSL https://raw.githubusercontent.com/Homebrew/install/HEAD/install.sh \
      -o "$SETUP_TMP_DIR/homebrew.sh"
    /bin/bash "$SETUP_TMP_DIR/homebrew.sh"
  fi
  [[ -x "$BREW_BIN" ]] || die "Homebrew was not installed at $BREW_BIN."
  eval "$("$BREW_BIN" shellenv)"
  BREW_PREFIX="$("$BREW_BIN" --prefix)"
  brew update
  success "Homebrew ready"

  # 2. Preserve existing runtime major versions for project compatibility.
  local brew_packages=(
    tailscale
    gh
    openjdk@21
    python@3.12
    uv
    ripgrep
    tmux
    jq
    shellcheck
    colima
    docker
    node@24
    can1357/tap/omp
  )
  local brew_casks=(
    codex
    gcloud-cli
  )
  info "Installing Homebrew formulae: ${brew_packages[*]}"
  brew install --formula "${brew_packages[@]}"
  info "Installing Homebrew casks: ${brew_casks[*]}"
  brew install --cask "${brew_casks[@]}"
  success "Homebrew packages ready"

  # 3. Oh My Zsh supplies its default theme on a fresh machine.
  # Keep an existing .zshrc and any custom theme or plugins.
  local omz_dir="${ZSH:-$HOME/.oh-my-zsh}"
  if [[ -d "$omz_dir" ]]; then
    info "Oh My Zsh already installed"
  else
    info "Installing Oh My Zsh..."
    curl -fsSL https://raw.githubusercontent.com/ohmyzsh/ohmyzsh/master/tools/install.sh \
      -o "$SETUP_TMP_DIR/ohmyzsh.sh"
    ZSH="$omz_dir" RUNZSH=no CHSH=no KEEP_ZSHRC=yes sh "$SETUP_TMP_DIR/ohmyzsh.sh"
  fi

  # 4. Set paths without force-linking keg-only packages over other versions.
  configure_shell "$HOME" "${ZDOTDIR:-$HOME}" "$BREW_BIN" "$BREW_PREFIX"
  # shellcheck disable=SC1091
  . "$HOME/.config/mac-mini-setup/env.sh"
  success "Shell paths configured (including Rust, uv tools, and Claude Code)"

  # 5. Rust via rustup, including cargo, rustfmt, and clippy.
  if command -v rustup >/dev/null 2>&1; then
    info "Installing/updating the stable Rust toolchain..."
    rustup toolchain install stable --profile default
    if ! rustup default >/dev/null 2>&1; then
      rustup default stable
    fi
  else
    info "Installing Rust with rustup..."
    curl --proto '=https' --tlsv1.2 -fsSL https://sh.rustup.rs \
      -o "$SETUP_TMP_DIR/rustup.sh"
    sh "$SETUP_TMP_DIR/rustup.sh" -y --no-modify-path --profile default --default-toolchain stable
  fi
  rustup component add --toolchain stable rustfmt clippy
  success "Rust ready"

  # 6. Claude Code's native installer manages its own updates.
  if command -v claude >/dev/null 2>&1; then
    info "Claude Code already installed"
  else
    info "Installing Claude Code..."
    curl -fsSL https://claude.ai/install.sh -o "$SETUP_TMP_DIR/claude.sh"
    bash "$SETUP_TMP_DIR/claude.sh"
  fi
  success "Claude Code ready"

  local tool
  for tool in gh rg tmux jq shellcheck colima docker node npm python3 java javac uv uvx rustup rustc cargo omp codex gcloud claude tailscale; do
    command -v "$tool" >/dev/null 2>&1 || die "Installed command is missing from PATH: $tool"
  done

  # 7. Headless Tailscale daemon; authenticate after setup.
  info "Starting Tailscale service..."
  sudo "$BREW_BIN" services start tailscale || warn "Start Tailscale manually: sudo $BREW_BIN services start tailscale"

  # 8. Keep the Mac available remotely; let its display sleep.
  if [[ "${CONFIGURE_POWER:-1}" == 1 ]]; then
    info "Applying power management settings..."
    sudo pmset -a sleep 0 disksleep 0 displaysleep 10 womp 1
    success "System sleep disabled; display sleeps after 10 minutes; Wake on LAN enabled"
  fi

  printf '\nSetup complete! Next steps:\n'
  printf '  Reload your shell:          exec zsh -l\n'
  printf '  Authenticate Tailscale:     sudo "%s/bin/tailscale" up\n' "$BREW_PREFIX"
  printf '  Authenticate GitHub CLI:    gh auth login\n'
  printf '  Configure Google Cloud:    gcloud init\n'
  printf '  Local Google SDK auth:     gcloud auth application-default login (if needed)\n'
  printf '  Start container runtime:   colima start\n'
  printf '  Sign in to coding tools:   run codex, claude, and omp\n'
  printf '  Install Grok Bot:          https://cursor.com/dashboard/bot (separate desktop app)\n'
  printf '  Verify runtimes:           node --version; python3 --version; java -version; rustc --version; uv --version\n'
}

if [[ "${BASH_SOURCE[0]}" == "$0" ]]; then
  main "$@"
fi
